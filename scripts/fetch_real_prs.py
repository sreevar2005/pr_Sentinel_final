"""Download the real pull request sample that `prscreen eval` uses to measure noise.

Selection rule, fixed before looking at any results so the sample cannot be cherry-picked: for
each repository below, the PER_REPO most recently merged pull requests whose diff is smaller
than MAX_BYTES, as of the day the script runs. Bot PRs (Dependabot, Renovate) are kept because
real repositories get them too.

All repositories are under permissive licenses; their diffs are stored unmodified with the
source URL and license in corpus/real/prs.toml.

Usage: uv run python scripts/fetch_real_prs.py  (needs network; unauthenticated API is enough)
"""

from __future__ import annotations

import json
import sys
import time
import urllib.request
from datetime import UTC, datetime
from pathlib import Path

REPOS = {
    "psf/requests": "Apache-2.0",
    "pallets/flask": "BSD-3-Clause",
    "encode/httpx": "BSD-3-Clause",
    "fastapi/fastapi": "MIT",
    "django/django": "BSD-3-Clause",
    "pytest-dev/pytest": "MIT",
    "expressjs/express": "MIT",
    "axios/axios": "MIT",
    "vitejs/vite": "MIT",
    "spf13/cobra": "Apache-2.0",
}
PER_REPO = 10
MAX_BYTES = 200_000
OUT = Path(__file__).resolve().parent.parent / "corpus" / "real"
HEADERS = {"User-Agent": "prscreen-eval-fetch", "Accept": "application/vnd.github+json"}


def _get(url: str, limit: int = 10_000_000) -> bytes:
    request = urllib.request.Request(url, headers=HEADERS)  # noqa: S310 - fixed https URLs
    with urllib.request.urlopen(request, timeout=60) as response:  # noqa: S310
        return bytes(response.read(limit + 1))


def _toml_str(value: str) -> str:
    """A TOML basic string with every non-ASCII character escaped (TOML rejects JSON's surrogate pairs)."""
    backslash = chr(92)
    out = []
    for ch in value:
        code = ord(ch)
        if ch in ('"', backslash):
            out.append(backslash + ch)
        elif 0x20 <= code < 0x7F:
            out.append(ch)
        elif code <= 0xFFFF:
            out.append(f"{backslash}u{code:04X}")
        else:
            out.append(f"{backslash}U{code:08X}")
    return '"' + "".join(out) + '"'


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob("*.diff"):
        old.unlink()
    entries: list[str] = []
    for repo, license_id in REPOS.items():
        listing = json.loads(
            _get(
                f"https://api.github.com/repos/{repo}/pulls?state=closed&sort=updated&direction=desc&per_page=60"
            )
        )
        merged = sorted(
            (pr for pr in listing if pr.get("merged_at")), key=lambda pr: pr["merged_at"], reverse=True
        )
        kept = 0
        for pr in merged:
            if kept == PER_REPO:
                break
            diff = _get(f"https://github.com/{repo}/pull/{pr['number']}.diff", MAX_BYTES)
            time.sleep(0.5)
            if len(diff) > MAX_BYTES or not diff.startswith(b"diff --git"):
                continue
            name = f"{repo.replace('/', '-')}-{pr['number']}.diff"
            (OUT / name).write_bytes(diff)
            entries.append(
                "[[pr]]\n"
                f"repo = {_toml_str(repo)}\nnumber = {pr['number']}\ntitle = {_toml_str(pr['title'])}\n"
                f"url = {_toml_str(pr['html_url'])}\nauthor = {_toml_str(pr['user']['login'])}\n"
                f"merged_at = {_toml_str(pr['merged_at'])}\nlicense = {_toml_str(license_id)}\n"
                f"file = {_toml_str(name)}\n"
            )
            kept += 1
        print(f"{repo}: {kept} PRs", file=sys.stderr)
    header = (
        "# Real merged pull requests used to measure noise. Generated by scripts/fetch_real_prs.py.\n"
        f"# Fetched {datetime.now(UTC).date().isoformat()}; selection rule documented in that script.\n\n"
    )
    (OUT / "prs.toml").write_text(header + "\n".join(entries), encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
